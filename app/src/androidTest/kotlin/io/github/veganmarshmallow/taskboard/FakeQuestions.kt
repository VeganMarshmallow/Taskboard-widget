/**
 * Task #82: a board repo with one of Claude's open questions (#12, waiting on the owner), an answered
 * question the owner asked about #17, and a general question (#90) Claude has not answered yet.
 */
object FakeQuestions {
    const val BOARD = "/repos/VeganMarshmallow/claude-workspace"
    private const val API = "https://api.github.com$BOARD"
    private const val FOOTER = "\\n\\n---\\n_Generated by [Claude Code](https://claude.ai/code)_"

    private val issues = """[
        {"number":12,"title":"Which charting library for the dashboard?","state":"open","labels":[{"name":"status: blocked"},{"name":"needs-owner"}],"body":"### Repo\n\nVeganMarshmallow/portfolio-site"},
        {"number":17,"title":"Weekly digest email of finished tasks","state":"open","labels":[{"name":"status: todo"}],"body":"Send a digest."},
        {"number":90,"title":"Question for Claude: How many CI minutes are left this month?","state":"open","labels":[{"name":"question-for-claude"},{"name":"status: todo"}],"body":"**Question for Claude:**\n\nHow many CI minutes are left this month?"}
    ]"""

    private val comments = """[
        {"id":5,"body":"**Answer:**\n\nYes: Mondays at 8:00, Israel time.$FOOTER","created_at":"2026-10-22T09:00:00Z","issue_url":"$API/issues/17"},
        {"id":4,"body":"**Question for Claude:**\n\nWill the digest go out on Mondays?","created_at":"2026-10-21T20:00:00Z","issue_url":"$API/issues/17"},
        {"id":3,"body":"⛔ Blocked: the dashboard needs a charting library.\n\n**What I need from you:** Chart.js (small) or ECharts (has heatmaps)?$FOOTER","created_at":"2026-10-21T10:00:00Z","issue_url":"$API/issues/12"}
    ]"""

    fun script(): (String, String) -> FakeGitHubServer.Answer? = { method, path ->
        when {
            method == "GET" && path.startsWith("$BOARD/issues/comments?") -> FakeGitHubServer.Answer(200, comments)
            method == "GET" && path.startsWith("$BOARD/issues?") && "state=open" in path -> FakeGitHubServer.Answer(200, issues)
            method == "GET" && path.startsWith("$BOARD/issues?") -> FakeGitHubServer.Answer(200, "[]")
            method == "POST" && path == "$BOARD/issues" -> FakeGitHubServer.Answer(201, """{"number":91,"labels":[{"name":"question-for-claude"},{"name":"status: todo"}]}""")
            method == "POST" && path.matches(Regex("$BOARD/issues/\\d+/comments")) -> FakeGitHubServer.Answer(201, """{"id":9}""")
            method == "POST" && path.matches(Regex("$BOARD/issues/\\d+/labels")) -> FakeGitHubServer.Answer(200, "[]")
            method == "DELETE" && path.contains("/labels/") -> FakeGitHubServer.Answer(200, "[]")
            else -> null
        }
    }

    private val instrumentation get() = InstrumentationRegistry.getInstrumentation()
    private val context: Context get() = instrumentation.targetContext

    fun serve(): FakeGitHubServer {
        val s = FakeGitHubServer(script())
        TestOverrides.httpClient = s::client
        TokenStore(context).save("github_pat_TESTONLY")
        StateStore(context).save(FakeMerges.boardState())
        return s
    }

    fun reset(server: FakeGitHubServer?) {
        server?.close()
        context.getSystemService(JobScheduler::class.java).cancelAll()
        TestOverrides.httpClient = null
        TokenStore(context).clear()
        StateStore(context).save(WidgetState.INITIAL)
    }

    @Suppress("UNCHECKED_CAST")
    fun <A : Activity> launch(type: Class<A>, intent: Intent): A {
        val monitor = instrumentation.addMonitor(type.name, null, false)
        try {
            context.startActivity(intent)
            return (monitor.waitForActivityWithTimeout(10_000) as A?).also { assertNotNull("activity launched", it) }!!
        } finally {
            instrumentation.removeMonitor(monitor)
        }
    }

    fun waitUntil(what: String, timeoutMs: Long = 20_000, condition: () -> Boolean) {
        val deadline = SystemClock.uptimeMillis() + timeoutMs
        while (SystemClock.uptimeMillis() < deadline) {
            var ok = false
            instrumentation.runOnMainSync { ok = condition() }
            if (ok) return
            SystemClock.sleep(100)
        }
        throw AssertionError("timed out waiting for: $what")
    }

    /** The widget refresh a posted question or reply starts has ended, so it can't leak into later tests. */
    fun waitForRefresh(server: FakeGitHubServer, before: Int) {
        waitUntil("the refresh after posting ended", timeoutMs = 60_000) {
            server.received.count { it.method == "GET" && it.path.startsWith("$BOARD/issues?") } > before &&
                AppGraph.refreshTracker(context).status() != RefreshTracker.Status.RUNNING
        }
    }

    /** Both lists are on screen: one question from Claude, two of the owner's. */
    fun loaded(activity: Activity): Boolean =
        activity.findViewById<ViewGroup>(R.id.questions_from_claude).childCount == 1 &&
            activity.findViewById<ViewGroup>(R.id.questions_to_claude).childCount == 2 &&
            activity.findViewById<View>(R.id.questions_status).visibility == View.GONE

    fun claudeCard(activity: Activity): View = activity.findViewById<ViewGroup>(R.id.questions_from_claude).getChildAt(0)

    fun askBox(activity: Activity): View = activity.findViewById(R.id.questions_ask)
}
