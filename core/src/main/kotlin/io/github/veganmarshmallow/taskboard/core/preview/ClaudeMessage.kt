package io.github.veganmarshmallow.taskboard.core.preview

import io.github.veganmarshmallow.taskboard.core.board.TitleCleaner
import io.github.veganmarshmallow.taskboard.core.markdown.MarkdownBlock
import io.github.veganmarshmallow.taskboard.core.markdown.MarkdownBlocks
import io.github.veganmarshmallow.taskboard.core.markdown.MarkdownInline
import io.github.veganmarshmallow.taskboard.core.markdown.PlainText

/**
 * A Claude comment as the preview shows it in full (task #43): plain text, one line per Markdown
 * block (list items start with [PlainText.BULLET]), without the `---` + "Generated by" footer.
 *
 * [needFromYou] is the comment's "What I need from you" part, without its label, when it has one;
 * the preview shows it first and highlighted. [body] is everything else. At least one of them has
 * visible text, otherwise [of] returns null.
 */
data class ClaudeMessage(val needFromYou: String?, val body: String) {
    companion object {
        /**
         * `**What I need from you:**`, `What I need from you —`, `### What I need from you` (heading
         * text), optionally after an emoji. Matched on the raw Markdown so the rest keeps its formatting.
         */
        private val NEED_LABEL = Regex(
            """^\s*(?:\p{So}️?\s*)?(?:[*_]{1,3})?\s*What I need from you(?![\p{L}\p{N}])[\s:：.?？!\-–—]*(?:[*_]{1,3})?[\s:：.?？!\-–—]*""",
            RegexOption.IGNORE_CASE,
        )
        private val FOOTER = Regex("""^(?:\p{So}️?\s*)?Generated (?:by|with)\b""", RegexOption.IGNORE_CASE)

        fun of(markdown: String): ClaudeMessage? {
            val blocks = withoutFooter(MarkdownBlocks.parse(markdown))
            val start = blocks.indexOfFirst { labelled(it) != null }
            val need = if (start < 0) null else needPart(blocks, start)
            val needText = need?.let { text(it.blocks) }?.takeIf(TaskSummary::isVisible)
            val rest = if (need == null) blocks else blocks.subList(0, start) + blocks.subList(need.end, blocks.size)
            val body = text(rest).takeIf(TaskSummary::isVisible).orEmpty()
            return if (needText == null && body.isEmpty()) null else ClaudeMessage(needText, body)
        }

        /** The blocks of the "What I need from you" part starting at [start], and the index after it. */
        private class NeedPart(val blocks: List<MarkdownBlock>, val end: Int)

        /**
         * The text after the label, then: for a heading, its section (up to the next heading of the
         * same or a higher level, or a `---`); for a paragraph, the list items and code blocks right
         * after it, or the next paragraph when there is neither text nor a list. A list item with text
         * after the label stands alone: the items after it are its siblings, not part of it.
         */
        private fun needPart(blocks: List<MarkdownBlock>, start: Int): NeedPart {
            val first = blocks[start]
            val out = ArrayList<MarkdownBlock>()
            labelled(first)?.takeIf { it.isNotBlank() }?.let { out.add(MarkdownBlock.Paragraph(it)) }
            var end = start + 1
            if (first is MarkdownBlock.Heading) {
                while (end < blocks.size && !endsSection(blocks[end], first.level)) out.add(blocks[end++])
                return NeedPart(out, end)
            }
            if (first is MarkdownBlock.ListItem && out.isNotEmpty()) return NeedPart(out, end)
            while (end < blocks.size && (blocks[end] is MarkdownBlock.ListItem || blocks[end] is MarkdownBlock.Code)) out.add(blocks[end++])
            if (out.isEmpty() && end < blocks.size && blocks[end] is MarkdownBlock.Paragraph) out.add(blocks[end++])
            return NeedPart(out, end)
        }

        private fun endsSection(block: MarkdownBlock, level: Int) =
            block is MarkdownBlock.Rule || (block is MarkdownBlock.Heading && block.level <= level)

        /** The raw text after the "What I need from you" label, or null when [block] does not start with it. */
        private fun labelled(block: MarkdownBlock): String? {
            val raw = rawText(block) ?: return null
            val m = NEED_LABEL.find(raw) ?: return null
            return raw.substring(m.range.last + 1)
        }

        /** Drops a trailing `---` with only a "Generated by …" line (or nothing) after it, or a bare last "Generated by" line. */
        private fun withoutFooter(blocks: List<MarkdownBlock>): List<MarkdownBlock> {
            val rule = blocks.indexOfLast { it is MarkdownBlock.Rule }
            if (rule >= 0 && blocks.subList(rule + 1, blocks.size).all(::isFooter)) return blocks.subList(0, rule)
            return if (blocks.lastOrNull()?.let(::isFooter) == true) blocks.dropLast(1) else blocks
        }

        private fun isFooter(block: MarkdownBlock): Boolean =
            rawText(block)?.let { FOOTER.containsMatchIn(MarkdownInline.strip(it)) } == true

        private fun rawText(block: MarkdownBlock): String? = when (block) {
            is MarkdownBlock.Heading -> block.text
            is MarkdownBlock.Paragraph -> block.text
            is MarkdownBlock.ListItem -> block.text
            MarkdownBlock.Rule, is MarkdownBlock.Code -> null
        }

        /** Plain text, each line cleaned of bidi controls and broken UTF-16, empty lines dropped. */
        private fun text(blocks: List<MarkdownBlock>): String = PlainText.lines(blocks)
            .lineSequence()
            .map(TitleCleaner::sanitize)
            .filter(TaskSummary::isVisible)
            .joinToString("\n")
    }
}
