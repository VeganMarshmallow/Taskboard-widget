/** Task #82: the question wording, the badge, the listings' parsing and the screen's state. */
class QuestionTextTest {
    @Test fun commentStartsWithThePrefixTheRulesLookFor() {
        assertEquals("**Question for Claude:**\n\nWhy so slow?", QuestionText.comment("  Why so slow?\n"))
        assertTrue(QuestionText.isQuestion(QuestionText.comment("x")))
        assertTrue(QuestionText.isQuestion("﻿  **question for claude:** x"))
        assertFalse(QuestionText.isQuestion("I have a **Question for Claude:** x"))
        assertTrue(QuestionText.isAnswer("**Answer:** yes"))
        assertFalse(QuestionText.isAnswer(""))
        assertEquals("yes", QuestionText.answerText("**Answer:**\n\nyes  "))
        assertEquals("plain", QuestionText.questionText("plain"))
    }

    @Test fun issueTitleUsesTheFirstLineAndIsShort() {
        assertEquals("Question for Claude: How much CI is left?", QuestionText.issueTitle("\n\n How much CI is left?\nmore"))
        assertTrue(QuestionText.issueTitle("y".repeat(500)).length <= QuestionText.TITLE_MAX)
        assertEquals("Question for Claude:", QuestionText.issueTitle("").trim())
    }

    @Test fun answerFooterMarksAClaudeComment() {
        assertTrue(ClaudeComments.isFromClaude("**Answer:** yes\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"))
        assertFalse(ClaudeComments.isFromClaude("**Answer:** yes"))
        assertFalse(ClaudeComments.isFromClaude(""))
    }

    @Test fun badgeCountsNeedsOwnerTasksOnce() {
        val board = BoardBuilder().build(
            listOf(issue(3, Labels.BLOCKED, Labels.NEEDS_OWNER), issue(4, Labels.TODO, Labels.NEEDS_OWNER), issue(5, Labels.TODO)),
            NOW,
        )
        assertEquals(2, QuestionBadge.count(board))
        assertEquals(0, QuestionBadge.count(null))
        assertEquals(listOf("?", "1", "9", "9+"), listOf(0, 1, 9, 10).map(QuestionBadge::text))
        assertEquals("?", QuestionBadge.text(-3))
        assertEquals(0, QuestionBadge.count(Board(BoardBuilder().build(emptyList(), NOW).sections, NOW)))
    }

    @Test fun repoCommentsKnowTheirIssue() {
        val body = """[
            {"id":5,"body":"🤖 Hi?","created_at":"2026-10-22T10:00:00Z","issue_url":"https://api.github.com/repos/o/r/issues/12"},
            {"id":6,"body":"no issue"},
            {"id":7,"issue_url":"https://api.github.com/repos/o/r/issues/13"},
            {"id":8,"body":"bad","issue_url":"https://api.github.com/repos/o/r/issues/0"}
        ]"""
        val parsed = QuestionsJsonParser.parseRepoComments(body)
        assertEquals(listOf(12), parsed.map { it.issue })
        assertEquals(5L, parsed.single().comment.id)
        assertTrue(QuestionsJsonParser.parseRepoComments("[]").isEmpty())
    }

    @Test(expected = MalformedResponseException::class) fun repoCommentsMustBeAnArray() {
        QuestionsJsonParser.parseRepoComments("{}")
    }

    @Test fun issuesListingKeepsBodies() {
        val parsed = QuestionsJsonParser.parseIssues("""[{"number":3,"title":"T","state":"open","labels":[{"name":"needs-owner"}],"body":"B"},{"number":4,"title":"U","state":"open","labels":[],"body":null}]""")
        assertEquals(listOf("B", ""), parsed.map { it.body })
        assertTrue(Labels.NEEDS_OWNER in parsed[0].issue.labels)
    }

    @Test fun screenKeepsQuestionsWhileReloadingAndAfterFailure() {
        val loaded = QuestionsScreen().loadStarted().loaded(io.github.veganmarshmallow.taskboard.core.questions.Questions.NONE)
        val failed = loaded.loadStarted().failed(io.github.veganmarshmallow.taskboard.core.error.BoardError.Network)
        assertEquals(loaded.questions, failed.questions)
        assertFalse(failed.loading)
        assertEquals(QuestionsScreen.GENERAL, loaded.askKey)
        val about = loaded.copy(topic = AskTopic(12, "T"))
        assertEquals(12, about.askKey)
        assertEquals(QuestionsScreen.GENERAL, about.askGeneral(about.ask).askKey)
    }
}
