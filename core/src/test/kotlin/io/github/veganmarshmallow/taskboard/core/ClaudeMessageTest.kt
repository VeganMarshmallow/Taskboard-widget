package io.github.veganmarshmallow.taskboard.core

import io.github.veganmarshmallow.taskboard.core.markdown.MarkdownBlocks
import io.github.veganmarshmallow.taskboard.core.markdown.PlainText
import io.github.veganmarshmallow.taskboard.core.preview.ClaudeComments
import io.github.veganmarshmallow.taskboard.core.preview.ClaudeMessage
import io.github.veganmarshmallow.taskboard.core.preview.IssueComment
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test

/** Task #43: Claude's latest comment in full, with the "What I need from you" part split out. */
class ClaudeMessageTest {
    private val footer = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"

    @Test fun realBlockedComment() {
        val m = ClaudeMessage.of(
            "⛔ Blocked: the repo has no **deploy key**.\n\n" +
                "**What I need from you:** give the workflow a `DEPLOY_KEY` secret. Then remove `needs-owner` and I'll continue." + footer,
        )!!
        assertEquals("give the workflow a DEPLOY_KEY secret. Then remove needs-owner and I'll continue.", m.needFromYou)
        assertEquals("⛔ Blocked: the repo has no deploy key.", m.body)
    }

    @Test fun withoutNeedTheWholeCommentIsTheBodyOneLinePerBlock() {
        val m = ClaudeMessage.of("🤖 Started in run 2026-10-30 10:00.\n\nPlan:\n- parser in core\n- 1. views" + footer)!!
        assertNull(m.needFromYou)
        assertEquals("🤖 Started in run 2026-10-30 10:00.\nPlan:\n• parser in core\n• 1. views", m.body)
    }

    @Test fun labelFollowedByAList() {
        val m = ClaudeMessage.of("⛔ Blocked\n\n**What I need from you**:\n- a token\n- the repo name\n\nThanks")!!
        assertEquals("• a token\n• the repo name", m.needFromYou)
        assertEquals("⛔ Blocked\nThanks", m.body)
    }

    @Test fun labelAloneTakesTheNextParagraph() {
        val m = ClaudeMessage.of("⛔ Blocked\n\nWhat I need from you:\n\nPick Chart.js or ECharts.\n\nMore context here.")!!
        assertEquals("Pick Chart.js or ECharts.", m.needFromYou)
        assertEquals("⛔ Blocked\nMore context here.", m.body)
    }

    @Test fun labelAsAHeadingTakesItsSection() {
        val m = ClaudeMessage.of("⛔ Blocked\n\n### What I need from you\nA token.\n- with repo scope\n\n### Details\nWhy it failed.")!!
        assertEquals("A token.\n• with repo scope", m.needFromYou)
        assertEquals("⛔ Blocked\nDetails\nWhy it failed.", m.body)
    }

    @Test fun labelVariants() {
        listOf(
            "What I need from you: X", "**What I need from you:** X", "**What I need from you** — X",
            "👉 **What I need from you:** X", "- **WHAT I NEED FROM YOU:** X", "__What I need from you__: X",
        ).forEach { assertEquals(it, "X", ClaudeMessage.of("⛔ Blocked\n\n$it")!!.needFromYou) }
    }

    @Test fun similarWordingIsNotTheLabel() {
        val m = ClaudeMessage.of("⛔ What I need from your side is unclear")!!
        assertNull(m.needFromYou)
        assertEquals("⛔ What I need from your side is unclear", m.body)
    }

    @Test fun onlyTheNeedPartLeavesAnEmptyBody() {
        val m = ClaudeMessage.of("**What I need from you:** a token" + footer)!!
        assertEquals("a token", m.needFromYou)
        assertEquals("", m.body)
    }

    @Test fun emptyLabelFallsBackToTheBody() {
        val m = ClaudeMessage.of("⛔ Blocked\n\n**What I need from you:**")!!
        assertNull(m.needFromYou)
        assertEquals("⛔ Blocked", m.body)
    }

    @Test fun nothingVisibleIsNull() {
        listOf("", "   ", "---", footer, "​‍", "```\n   \n```").forEach { assertNull(it, ClaudeMessage.of(it)) }
    }

    @Test fun footerVariants() {
        assertEquals("✅ Done", ClaudeMessage.of("✅ Done\n\n---\n🤖 Generated with [Claude Code](https://claude.com/claude-code)")!!.body)
        assertEquals("✅ Done", ClaudeMessage.of("✅ Done\n\n_Generated by Claude Code_")!!.body)
        assertEquals("✅ Done", ClaudeMessage.of("✅ Done\n\n---")!!.body)
        // A rule followed by real content is not a footer; the rule itself is not shown.
        assertEquals("✅ Done\nNotes after the rule", ClaudeMessage.of("✅ Done\n\n---\n\nNotes after the rule")!!.body)
        // "Generated by" in the middle is ordinary text.
        assertEquals("✅ Done\nGenerated by the build: 3 files\nEnd", ClaudeMessage.of("✅ Done\n\nGenerated by the build: 3 files\n\nEnd")!!.body)
    }

    @Test fun hebrewAndRtlControls() {
        val m = ClaudeMessage.of("⛔ חסום: אין **מפתח**.\n\n**What I need from you:** ‫להוסיף סוד‬ בשם `KEY`.")!!
        assertEquals("להוסיף סוד בשם KEY.", m.needFromYou)
        assertEquals("⛔ חסום: אין מפתח.", m.body)
    }

    @Test fun linksImagesAndHtmlAreStripped() {
        val m = ClaudeMessage.of("✅ PR: [#12](https://github.com/x/y/pull/12) ![shot](a.png) <b>ok</b> &amp; done")!!
        assertEquals("✅ PR: #12 shot ok & done", m.body)
    }

    @Test fun hugeCommentIsBoundedAndDoesNotThrow() {
        val long = "🤖 " + (1..20_000).joinToString("\n\n") { "Paragraph $it with *some* text." }
        val m = ClaudeMessage.of(long)!!
        assertTrue(m.body.length <= PlainText.MAX_LINES_OUTPUT + 2_100)
        assertTrue(m.body.startsWith("🤖 Paragraph 1 with some text.\nParagraph 2"))
        ClaudeMessage.of("*".repeat(50_000))
        ClaudeMessage.of("**What I need from you:** " + "_".repeat(50_000))
    }

    @Test fun latestMessagePicksTheNewestClaudeComment() {
        val comments = listOf(
            IssueComment(1, "🤖 Started", null),
            IssueComment(2, "​⛔ Blocked\n\n**What I need from you:** a token", null),
            IssueComment(3, "owner: ok", null),
        )
        assertEquals(ClaudeMessage("a token", "⛔ Blocked"), ClaudeComments.latestMessage(comments))
        assertNull(ClaudeComments.latestMessage(listOf(IssueComment(1, "owner only", null))))
        assertNull(ClaudeComments.latestMessage(emptyList()))
    }

    @Test fun plainTextLinesKeepsOneLinePerBlock() {
        assertEquals("Title\nPara one two\n• item\ncode", PlainText.lines(MarkdownBlocks.parse("# Title\nPara\none two\n\n---\n- item\n```\ncode\n```")))
        assertEquals("", PlainText.lines(emptyList()))
    }

    // --- review of #43: edge cases ---

    @Test fun windowsLineEndings() {
        val m = ClaudeMessage.of("⛔ Blocked\r\n\r\n**What I need from you:**\r\n- a\r\n- b\r\n\r\n---\r\n_Generated by Claude Code_")!!
        assertEquals("• a\n• b", m.needFromYou)
        assertEquals("⛔ Blocked", m.body)
    }

    @Test fun labelInAListItemDoesNotTakeItsSiblings() {
        val m = ClaudeMessage.of("✅ Summary:\n- Done: x\n- **What I need from you:** y\n- Next: z")!!
        assertEquals("y", m.needFromYou)
        assertEquals("✅ Summary:\n• Done: x\n• Next: z", m.body)
        // A bare label item takes the items after it (nesting is not tracked).
        assertEquals("• a\n• b", ClaudeMessage.of("⛔ B\n\n- What I need from you:\n  - a\n  - b")!!.needFromYou)
    }

    @Test fun labelWithAQuestionOrExclamationMark() {
        assertEquals("pick one", ClaudeMessage.of("⛔ B\n\n**What I need from you?** pick one")!!.needFromYou)
        assertEquals("pick one", ClaudeMessage.of("⛔ B\n\nWhat I need from you! pick one")!!.needFromYou)
    }

    @Test fun labelInAQuoteOrNumberedItemOrHeadingWithColon() {
        assertEquals("quoted", ClaudeMessage.of("> **What I need from you:** quoted")!!.needFromYou)
        assertEquals("num", ClaudeMessage.of("1. **What I need from you:** num")!!.needFromYou)
        val m = ClaudeMessage.of("## What I need from you:\nX\n## Next\nY")!!
        assertEquals("X", m.needFromYou)
        assertEquals("Next\nY", m.body)
    }

    @Test fun codeIsShownAsItsLinesAndBelongsToTheNeedPart() {
        val m = ClaudeMessage.of("⛔ Blocked\n\n**What I need from you:** run this:\n```sh\ngh secret set KEY\n```\n\nThanks")!!
        assertEquals("run this:\ngh secret set KEY", m.needFromYou)
        assertEquals("⛔ Blocked\nThanks", m.body)
        // In the body, code keeps Markdown characters verbatim (no stripping inside code).
        assertEquals("✅ Done\nval x = a*b*c", ClaudeMessage.of("✅ Done\n\n```\nval x = a*b*c\n\n```")!!.body)
    }

    @Test fun onlyTheFirstLabelIsSplitOut() {
        val m = ClaudeMessage.of("⛔ A\n\n**What I need from you:** one\n\nMore\n\n**What I need from you:** two")!!
        assertEquals("one", m.needFromYou)
        assertEquals("⛔ A\nMore\nWhat I need from you: two", m.body)
    }

    @Test fun labelAtTheEndBeforeTheFooter() {
        val m = ClaudeMessage.of("⛔ Blocked: long story.\n\n**What I need from you:** a token$footer")!!
        assertEquals("a token", m.needFromYou)
        assertEquals("⛔ Blocked: long story.", m.body)
        // An empty label with only the footer after it shows nothing extra.
        assertEquals(ClaudeMessage(null, "⛔ Blocked"), ClaudeMessage.of("⛔ Blocked\n\n#### What I need from you$footer"))
    }

    @Test fun mixedDirectionTextKeepsItsOrderAndDropsBidiOverrides() {
        val m = ClaudeMessage.of("⛔ חסום ב־PR [#12](https://x.y) של `api`\n\n**What I need from you:** \u202Eלאשר\u202C את ה־merge")!!
        assertEquals("לאשר את ה־merge", m.needFromYou)
        assertEquals("⛔ חסום ב־PR #12 של api", m.body)
    }
}
