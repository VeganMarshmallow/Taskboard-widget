/** Task #82, reviewer's edge cases: footer false positives, answers without a footer, failures, limits. */
class QuestionsEdgeCaseTest {
    private val repo = "https://api.github.com/repos/VeganMarshmallow/claude-workspace"
    private val footer = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"
    private fun api(http: FakeHttp) = GitHubApi(http, TOKEN, FIXED_CLOCK)

    private fun task(number: Int, vararg labels: String, body: String = "") =
        IssueDetails(Issue(number, "Task $number", labels.map(Labels::normalize).toSet(), true), body)

    private fun c(id: Long, body: String, minute: Int) =
        IssueComment(id, body, Instant.parse("2026-10-22T10:00:00Z").plusSeconds(minute * 60L))

    // --- Claude-footer detection ---

    @Test fun ownerReplyQuotingClaudesFooterIsTheOwners() {
        assertFalse(ClaudeComments.isFromClaude("> ⛔ Blocked. A or B?\n> ---\n> _Generated by [Claude Code](https://claude.ai/code)_\n\nB, thanks"))
        assertFalse(ClaudeComments.isFromClaude("B, thanks\n\n> _Generated by [Claude Code](https://claude.ai/code)_"))
        assertFalse(ClaudeComments.isFromClaude("Generated by [Claude Code] is what the footer says\n\nbut this is me"))
        assertFalse(ClaudeComments.isFromClaude("   \n\n  "))
        assertTrue(ClaudeComments.isFromClaude("**Answer:** yes$footer\n\n"))
        assertTrue(ClaudeComments.isFromClaude("x".repeat(100_000) + footer))
    }

    @Test fun anOwnerReplyThatQuotesTheQuestionStillHidesIt() {
        val question = "⛔ Blocked.\n\n**What I need from you:** A or B?$footer"
        val reply = question.lines().joinToString("\n") { "> $it" } + "\n\nB"
        val q = QuestionFinder.find(listOf(task(12, Labels.NEEDS_OWNER)), mapOf(12 to listOf(c(1, question, 1), c(2, reply, 2))))
        assertTrue(q.fromClaude.isEmpty())
    }

    @Test fun claudesAnswerWithoutAFooterDoesNotHideItsOpenQuestion() {
        val comments = listOf(
            c(1, "${QuestionText.ASK_PREFIX} Is CI green?", 0),
            c(2, "🤖 Should the badge count Done tasks too?", 1),
            c(3, "${QuestionText.ANSWER_PREFIX} Yes, CI is green.", 2), // no footer
        )
        val q = QuestionFinder.find(listOf(task(7)), mapOf(7 to comments))
        assertEquals(listOf(7), q.fromClaude.map { it.issue })
        assertEquals("Yes, CI is green.", q.toClaude.single().answer!!.body)
    }

    @Test fun anOwnerQuestionQuotingAFooterIsStillTheOwnersQuestion() {
        val body = "${QuestionText.ASK_PREFIX} about this:\n\n> _Generated by [Claude Code](https://claude.ai/code)_"
        val q = QuestionFinder.find(listOf(task(7)), mapOf(7 to listOf(c(1, body, 1)))).toClaude
        assertEquals(1, q.size)
        assertFalse(q.single().answered)
    }

    // --- Asking: failures and limits ---

    @Test fun aRefusedCommentAddsNoLabel() {
        for (code in listOf(401, 403, 404, 422)) {
            val http = FakeHttp().on({ it.url.endsWith("/comments") }) { status(code) }
            val result = AskService(api(http)).ask(12, "Why?")
            assertTrue("$code", result is ReplyResult.Failed)
            assertFalse("$code", (result as ReplyResult.Failed).mayHavePosted)
            assertEquals("$code", 1, http.requests.size)
        }
    }

    @Test fun aNetworkErrorOnTheCommentIsAFailure() {
        val http = FakeHttp().on({ true }) { throw IOException("reset") }
        assertTrue(AskService(api(http)).ask(12, "Why?") is ReplyResult.Failed)
        assertFalse(http.requests.any { it.url.endsWith("/labels") })
    }

    @Test fun aFailedGeneralQuestionPostsNothingElse() {
        for (code in listOf(403, 500)) {
            val http = FakeHttp().on({ it.method == "POST" && it.url == "$repo/issues" }) { status(code) }
            assertTrue("$code", AskService(api(http)).ask(null, "Which repo?") is ReplyResult.Failed)
            assertEquals("$code", 1, http.requests.size)
        }
    }

    @Test fun aQuestionExactlyAtGitHubsLimitIsSent() {
        val room = ReplyText.MAX_LENGTH - QuestionText.comment("").length
        val http = FakeHttp()
            .on({ it.url.endsWith("/comments") }) { status(201, body = "{}") }
            .on({ it.url.endsWith("/labels") }) { ok("[]") }
        assertEquals(ReplyResult.Sent(unblocked = false), AskService(api(http)).ask(12, "q".repeat(room)))
        val tooLong = FakeHttp()
        assertTrue(AskService(api(tooLong)).ask(12, "q".repeat(room + 1)) is ReplyResult.Failed)
        assertTrue(tooLong.requests.isEmpty())
    }

    // --- Loading: failures and caps ---

    @Test fun aFailedTaskListingFailsTheLoadBeforeReadingComments() {
        for (code in listOf(401, 403)) {
            val http = FakeHttp().on({ "state=open" in it.url }) { status(code) }.on({ true }) { ok("[]") }
            assertTrue("$code", QuestionsLoader(api(http)).load() is Outcome.Failure)
            assertFalse("$code", http.requests.any { "/issues/comments?" in it.url })
        }
        val offline = FakeHttp().on({ true }) { throw IOException("offline") }
        assertTrue(QuestionsLoader(api(offline)).load() is Outcome.Failure)
    }

    @Test fun theCommentsListingStopsAtItsPageCap() {
        var served = 0
        val http = FakeHttp()
            .on({ "/issues/comments" in it.url }) {
                served++
                ok(
                    """[{"id":$served,"body":"🤖 Which one $served?","created_at":"2026-10-22T09:00:00Z","issue_url":"$repo/issues/7"}]""",
                    "link" to """<$repo/issues/comments?page=${served + 1}>; rel="next"""",
                )
            }
            .on({ "state=open" in it.url }) { ok("""[{"number":7,"title":"T","state":"open","labels":[],"body":""}]""") }
            .on({ "state=closed" in it.url }) { ok("[]") }
        val questions = (QuestionsLoader(api(http)).load() as Outcome.Success).value
        assertEquals(QuestionsApi.COMMENT_PAGES, served)
        assertEquals(listOf(7), questions.fromClaude.map { it.issue })
    }

    @Test fun backfillIsCappedAtTenTasks() {
        val tasks = (2..13).joinToString(",") { """{"number":$it,"title":"T$it","state":"open","labels":[{"name":"needs-owner"}],"body":""}""" }
        val perTask = Regex("""/issues/\d+/comments""")
        val http = FakeHttp()
            .on({ "/issues/comments?" in it.url }) { ok("[]") }
            .on({ perTask.containsMatchIn(it.url) }) { ok("[]") }
            .on({ "state=open" in it.url }) { ok("[$tasks]") }
            .on({ "state=closed" in it.url }) { ok("[]") }
        val questions = (QuestionsLoader(api(http)).load() as Outcome.Success).value
        assertEquals(QuestionsLoader.MAX_BACKFILL, http.requests.count { perTask.containsMatchIn(it.url) })
        assertEquals(12, questions.fromClaude.size) // all still listed; ten with their text looked up
    }

    @Test fun anEmptyBoardHasNoQuestions() {
        val http = FakeHttp().on({ true }) { ok("[]") }
        val questions = (QuestionsLoader(api(http)).load() as Outcome.Success).value
        assertTrue(questions.fromClaude.isEmpty() && questions.toClaude.isEmpty())
        assertEquals(0, questions.waitingOnClaude)
    }
}
