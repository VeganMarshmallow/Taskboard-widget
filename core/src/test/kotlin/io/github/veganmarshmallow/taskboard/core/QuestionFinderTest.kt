package io.github.veganmarshmallow.taskboard.core

import io.github.veganmarshmallow.taskboard.core.model.Issue
import io.github.veganmarshmallow.taskboard.core.model.Labels
import io.github.veganmarshmallow.taskboard.core.preview.IssueComment
import io.github.veganmarshmallow.taskboard.core.preview.IssueDetails
import io.github.veganmarshmallow.taskboard.core.questions.ClaudeAsks
import io.github.veganmarshmallow.taskboard.core.questions.QuestionFinder
import io.github.veganmarshmallow.taskboard.core.questions.QuestionText
import io.github.veganmarshmallow.taskboard.core.preview.ClaudeMessage
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test
import java.time.Instant

/** Task #82: finding Claude's open questions and the owner's questions to Claude. */
class QuestionFinderTest {
    private val footer = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"

    private fun task(number: Int, vararg labels: String, body: String = "", open: Boolean = true, title: String = "Task $number") =
        IssueDetails(Issue(number, title, labels.map(Labels::normalize).toSet(), open), body)

    private fun c(id: Long, body: String, minute: Int?) =
        IssueComment(id, body, minute?.let { Instant.parse("2026-10-22T10:00:00Z").plusSeconds(it * 60L) })

    private fun find(tasks: List<IssueDetails>, vararg comments: Pair<Int, List<IssueComment>>) =
        QuestionFinder.find(tasks, comments.toMap())

    @Test fun needsOwnerTaskIsListedWithClaudesLatestComment() {
        val q = find(
            listOf(task(12, Labels.BLOCKED, Labels.NEEDS_OWNER)),
            12 to listOf(c(1, "🤖 Started. Plan: build it", 0), c(2, "⛔ Blocked.\n\n**What I need from you:** Chart.js or ECharts?$footer", 5)),
        ).fromClaude.single()
        assertEquals(12, q.issue)
        assertTrue(q.needsOwner)
        assertEquals("Chart.js or ECharts?", q.message!!.needFromYou)
        assertEquals("⛔ Blocked.", q.message!!.body) // as the preview shows it
    }

    @Test fun needsOwnerWithoutAnyClaudeCommentStillListed() {
        val q = find(listOf(task(5, Labels.NEEDS_OWNER))).fromClaude.single()
        assertNull(q.message)
        assertTrue(q.needsOwner)
    }

    @Test fun latestClaudeCommentThatAsksIsListedWithoutNeedsOwner() {
        val q = find(listOf(task(7, Labels.IN_PROGRESS)), 7 to listOf(c(1, "🤖 Should the badge count Done tasks too?", 1)))
            .fromClaude.single()
        assertFalse(q.needsOwner)
    }

    @Test fun commentWithFooterOnlyCountsAsClaude() {
        val q = find(listOf(task(7)), 7 to listOf(c(1, "Which colour do you want?$footer", 1))).fromClaude
        assertEquals(1, q.size)
    }

    @Test fun claudeCommentThatDoesNotAskIsNotAQuestion() {
        val q = find(listOf(task(7, Labels.IN_PROGRESS)), 7 to listOf(c(1, "🤖 Started. Plan: build the thing", 1)))
        assertTrue(q.fromClaude.isEmpty())
    }

    @Test fun onlyTheLatestClaudeCommentCounts() {
        val q = find(listOf(task(7)), 7 to listOf(c(1, "🤖 Which one?", 1), c(2, "✅ Done, PR open", 2)))
        assertTrue(q.fromClaude.isEmpty())
    }

    @Test fun ownerAnsweredAfterHidesTheQuestionEvenWithNeedsOwner() {
        val q = find(
            listOf(task(12, Labels.NEEDS_OWNER), task(13)),
            12 to listOf(c(1, "⛔ Which one?", 1), c(2, "ECharts", 2)),
            13 to listOf(c(3, "🤖 Which one?", 1), c(4, "ECharts", 2)),
        )
        assertTrue(q.fromClaude.isEmpty())
    }

    @Test fun ownerCommentBeforeTheQuestionDoesNotHideIt() {
        val q = find(listOf(task(12)), 12 to listOf(c(1, "please do X", 1), c(2, "🤖 X or Y?", 2)))
        assertEquals(1, q.fromClaude.size)
    }

    @Test fun commentsAreOrderedByTimeNotListOrder() {
        // The repo-wide listing is newest first.
        val q = find(listOf(task(12)), 12 to listOf(c(2, "🤖 X or Y?", 2), c(1, "please do X", 1)))
        assertEquals(1, q.fromClaude.size)
    }

    @Test fun claudesAnswerIsNotItsQuestion() {
        val q = find(
            listOf(task(12)),
            12 to listOf(c(1, "${QuestionText.ASK_PREFIX}\n\nWhy?", 1), c(2, "${QuestionText.ANSWER_PREFIX} Because. Anything else?$footer", 2)),
        )
        assertTrue(q.fromClaude.isEmpty())
        assertEquals("Because. Anything else?", q.toClaude.single().answer!!.body)
    }

    @Test fun closedTasksPullRequestsAndTheBoardSummaryAreSkipped() {
        val q = find(
            listOf(task(1, Labels.NEEDS_OWNER), task(2, Labels.NEEDS_OWNER, open = false), IssueDetails(Issue(3, "PR", setOf(Labels.NEEDS_OWNER), true, isPullRequest = true), "")),
        )
        assertTrue(q.fromClaude.isEmpty())
    }

    @Test fun needsOwnerComesFirstThenOldestTask() {
        val q = find(listOf(task(9), task(4, Labels.NEEDS_OWNER), task(3)), 9 to listOf(c(1, "🤖 A?", 1)), 3 to listOf(c(2, "🤖 B?", 1)))
        assertEquals(listOf(4, 3, 9), q.fromClaude.map { it.issue })
    }

    @Test fun ownerQuestionWaitsUntilAnswered() {
        val q = find(listOf(task(12)), 12 to listOf(c(1, "${QuestionText.ASK_PREFIX}\n\nIs the API rate limited?", 1)))
        val asked = q.toClaude.single()
        assertEquals("Is the API rate limited?", asked.question)
        assertNull(asked.answer)
        assertFalse(asked.general)
        assertEquals(1, q.waitingOnClaude)
    }

    @Test fun answerMatchesEveryEarlierOpenQuestionOnly() {
        val q = find(
            listOf(task(12)),
            12 to listOf(
                c(1, "${QuestionText.ASK_PREFIX} one", 1),
                c(2, "${QuestionText.ASK_PREFIX} two", 2),
                c(3, "${QuestionText.ANSWER_PREFIX} both: yes$footer", 3),
                c(4, "${QuestionText.ASK_PREFIX} three", 4),
            ),
        ).toClaude
        assertEquals(listOf("three", "two", "one"), q.map { it.question })
        assertEquals(listOf(false, true, true), q.map { it.answered })
        assertEquals("both: yes", q[1].answer!!.body)
    }

    @Test fun answerBeforeAnyQuestionIsIgnored() {
        val q = find(listOf(task(12)), 12 to listOf(c(1, "${QuestionText.ANSWER_PREFIX} x", 1), c(2, "${QuestionText.ASK_PREFIX} y", 2)))
        assertFalse(q.toClaude.single().answered)
    }

    @Test fun generalQuestionIssueBodyIsAQuestion() {
        val q = find(
            listOf(task(90, Labels.QUESTION_FOR_CLAUDE, Labels.TODO, body = QuestionText.comment("How much CI is left?"))),
            90 to listOf(c(1, "${QuestionText.ANSWER_PREFIX}\n\nAbout 900 minutes.$footer", 5)),
        ).toClaude.single()
        assertTrue(q.general)
        assertEquals("How much CI is left?", q.question)
        assertEquals("About 900 minutes.", q.answer!!.body)
    }

    @Test fun doneGeneralQuestionStillShowsItsAnswer() {
        val q = find(listOf(task(90, Labels.DONE, body = QuestionText.comment("Q?"), open = false)), 90 to listOf(c(1, "${QuestionText.ANSWER_PREFIX} A$footer", 1)))
        assertEquals("A", q.toClaude.single().answer!!.body)
        assertTrue(q.fromClaude.isEmpty())
    }

    @Test fun emptyQuestionAndEmptyAnswerAreIgnored() {
        val q = find(listOf(task(12)), 12 to listOf(c(1, QuestionText.ASK_PREFIX, 1), c(2, "${QuestionText.ASK_PREFIX} real", 2), c(3, "${QuestionText.ANSWER_PREFIX}   $footer", 3)))
        val asked = q.toClaude.single()
        assertEquals("real", asked.question)
        assertFalse("an answer with no text does not answer", asked.answered)
    }

    @Test fun answeredQuestionsAreCapped() {
        val comments = (1..30).flatMap { listOf(c(it * 2L, "${QuestionText.ASK_PREFIX} q$it", it * 2), c(it * 2L + 1, "${QuestionText.ANSWER_PREFIX} a$it", it * 2 + 1)) }
        val q = find(listOf(task(12)), 12 to comments).toClaude
        assertEquals(QuestionFinder.MAX_ANSWERED, q.size)
        assertEquals("q30", q.first().question)
    }

    @Test fun nothingAtAll() {
        val q = find(emptyList())
        assertTrue(q.fromClaude.isEmpty() && q.toClaude.isEmpty())
        assertTrue(find(listOf(task(3)), 3 to emptyList()).fromClaude.isEmpty())
    }

    @Test fun hugeBodiesAreCutNotRejected() {
        val huge = "🤖 " + "x".repeat(500_000) + "\n\nWhich one?"
        val q = find(listOf(task(12, Labels.NEEDS_OWNER)), 12 to listOf(c(1, huge, 1)))
        val message = q.fromClaude.single().message!!
        assertTrue(message.body.length <= QuestionFinder.MAX_BODY)
    }

    @Test fun missingTimesKeepListOrder() {
        val q = find(listOf(task(12)), 12 to listOf(c(1, "🤖 A or B?", null), c(2, "B", null)))
        assertTrue(q.fromClaude.isEmpty())
    }

    @Test fun asksDetection() {
        assertTrue(ClaudeAsks.asks(ClaudeMessage("Pick one", "")))
        assertTrue(ClaudeAsks.asks(ClaudeMessage(null, "Line\nShould I use **ECharts?**")))
        assertTrue(ClaudeAsks.asks(ClaudeMessage(null, "באיזה צבע？")))
        assertFalse(ClaudeAsks.asks(ClaudeMessage(null, "See https://x.example/?a=1 for details")))
        assertFalse(ClaudeAsks.asks(null))
    }
}
